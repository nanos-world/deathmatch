-- Helper for getting the correct announcer and label from kill count multi kill
function GetMultiKillLabel(kill_count)
	if (kill_count == 2) then return "DOUBLE KILL", "unreal-tournament-announcer::A_DoubleKill", 25 end
	if (kill_count == 3) then return "TRIPLE KILL", "unreal-tournament-announcer::A_TripleKill", 50 end
	if (kill_count == 4) then return "MULTI KILL", "unreal-tournament-announcer::A_MultiKill", 100 end
	if (kill_count == 5) then return "MEGA KILL!", "unreal-tournament-announcer::A_MegaKill", 200 end
	if (kill_count == 6) then return "ULTRA KILL!!", "unreal-tournament-announcer::A_UltraKill", 300 end

	return "MONSTER KILL!!!", "unreal-tournament-announcer::A_MonsterKill", 500
end

-- Helper for getting the correct announcer and label from kill count kill streak
function GetKillStreakLabel(kill_count)
	if (kill_count == 5) then return "KILLING SPREE", "unreal-tournament-announcer::A_KillingSpree", 100 end
	if (kill_count == 10) then return "RAMPAGE!", "unreal-tournament-announcer::A_Rampage", 200 end
	if (kill_count == 15) then return "DOMINATING!!", "unreal-tournament-announcer::A_Dominating", 300 end
	if (kill_count == 20) then return "UNSTOPPABLE!!!", "unreal-tournament-announcer::A_Unstoppable", 400 end
	if (kill_count >= 25) then return "GODLIKE!!!!!", "unreal-tournament-announcer::A_Godlike", 500 end

	return nil
end

-- Helper for getting the correct announcer countdown
function GetCountdownAnnouncer()
	if (Deathmatch.remaining_time == 300) then return "unreal-tournament-announcer::A_Countdown_05_Minutes" end
	if (Deathmatch.remaining_time == 180) then return "unreal-tournament-announcer::A_Countdown_03_Minutes" end
	if (Deathmatch.remaining_time == 60) then return "unreal-tournament-announcer::A_Countdown_01_Minute" end
	if (Deathmatch.remaining_time == 30) then return "unreal-tournament-announcer::A_Countdown_30_Seconds" end
	if (Deathmatch.remaining_time == 10) then return "unreal-tournament-announcer::A_Countdown_10" end
	if (Deathmatch.remaining_time == 9) then return "unreal-tournament-announcer::A_Countdown_09" end
	if (Deathmatch.remaining_time == 8) then return "unreal-tournament-announcer::A_Countdown_08" end
	if (Deathmatch.remaining_time == 7) then return "unreal-tournament-announcer::A_Countdown_07" end
	if (Deathmatch.remaining_time == 6) then return "unreal-tournament-announcer::A_Countdown_06" end
	if (Deathmatch.remaining_time == 5) then return "unreal-tournament-announcer::A_Countdown_05" end
	if (Deathmatch.remaining_time == 4) then return "unreal-tournament-announcer::A_Countdown_04" end
	if (Deathmatch.remaining_time == 3) then return "unreal-tournament-announcer::A_Countdown_03" end
	if (Deathmatch.remaining_time == 2) then return "unreal-tournament-announcer::A_Countdown_02" end
	if (Deathmatch.remaining_time == 1) then return "unreal-tournament-announcer::A_Countdown_01" end

	return nil
end